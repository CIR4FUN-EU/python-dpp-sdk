"""Generate docs/dpp4fun-fields.md from the bundled DPP4Fun semantic profile.

Run from the repository root: ``python scripts/generate_dpp4fun_fields.py``.
A documentation test fails when the committed file differs from this output.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / "src" / "dpp_sdk" / "dpp4fun" / "semantic" / "dpp4fun-semantic-profile-v1.json"
OUTPUT = ROOT / "docs" / "dpp4fun-fields.md"

KINDS = {
    "DataElementCollection": "collection",
    "SingleValuedDataElement": "single value",
    "MultiValuedDataElement": "list",
    "MultiLanguageDataElement": "multi-language text",
}

HEADER = """\
# DPP4Fun field reference

<!-- Generated by scripts/generate_dpp4fun_fields.py from the bundled semantic profile.
     Do not edit by hand; rerun the script instead. -->

This page lists every field of the DPP4Fun furniture profile that `dpp_sdk.dpp4fun` knows.
Use it to find the names you pass to the typed classes.

How to read the tables:

- **Field** is the path inside the aspect. Pass the first segment as a keyword to
  `Aspect.create(...)` or as the name to `with_field()`, `field()`, and `quantity()`. Names are the
  camelCase element IDs used in JSON, for example `Nameplate.create(manufacturerName="...")`.
  An unknown name raises `KeyError`.
- A path with `[*]` is one item of a repeated list. Build items with the composite class shown in
  the table and pass their elements as a tuple, for example
  `BillOfMaterials.create(materialSet=(Material.create(name="Oak").element,))`.
- Dotted paths without `[*]` are nested collections; build them with the composite class shown
  (for example `Contact`, `Address`).
- **Unit** names the unit dimension. Set such values with
  `with_quantity(name, Dpp4FunQuantity(value=..., unit=...))`; the matching `...Unit` field is
  filled for you.
- **Occurs** is how often the field may appear (`0..1` optional, `0..*` any number).

All fields are optional at construction. Run `validate_dpp4fun()` to check the profile rules.
"""


def _composites() -> dict[str, str]:
    """Map profile paths to the composite class names that build them."""
    sys.path.insert(0, str(ROOT / "src"))
    from dpp_sdk.dpp4fun import composites

    names: dict[str, list[str]] = {}
    for name in sorted(dir(composites)):
        value = getattr(composites, name)
        path = getattr(value, "profile_path", None)
        if isinstance(value, type) and isinstance(path, str) and not name.startswith("_"):
            names.setdefault(path, []).append(f"`{name}`")
    return {path: " / ".join(found) for path, found in names.items()}


def _occurs(definition: dict[str, object]) -> str:
    occurrence = definition.get("bindingOccurrence") or {}
    assert isinstance(occurrence, dict)
    low = occurrence.get("min", 0)
    high = occurrence.get("max")
    return f"{low}..{'*' if high is None else high}"


def _unit(definition: dict[str, object]) -> str:
    dimension = definition.get("unitDimension")
    if not dimension or str(dimension).endswith("-unit"):
        return ""
    return str(dimension)


def _section_title(root: str, applies_to: str) -> tuple[str, str]:
    if applies_to.startswith("characteristics-"):
        variant = applies_to.removeprefix("characteristics-")
        cls = variant[0].upper() + variant[1:] + "Characteristics"
        return f"{cls} (`characteristics`)", cls
    cls = root[0].upper() + root[1:]
    return f"{cls} (`{root}`)", cls


def render() -> str:
    profile = json.loads(PROFILE.read_text(encoding="utf-8"))
    composites = _composites()
    sections: dict[tuple[str, str], list[dict[str, object]]] = {}
    for definition in profile["definitions"]:
        path = str(definition["path"])
        root = path.split(".")[0].split("[")[0]
        sections.setdefault((root, definition["appliesTo"][0]), []).append(definition)

    general = sorted(key for key in sections if key[1] == "general")
    variants = sorted(key for key in sections if key[1] != "general")
    lines = [HEADER]
    for heading, keys in (("General aspects", general), ("Product types", variants)):
        lines.append(f"## {heading}\n")
        for root, applies_to in keys:
            title, cls = _section_title(root, applies_to)
            lines.append(f"### {title}\n")
            lines.append(f"Build with `{cls}.create(...)`.\n")
            lines.append("| Field | Kind | Datatype | Unit | Occurs | Build with |")
            lines.append("| --- | --- | --- | --- | --- | --- |")
            for definition in sections[(root, applies_to)]:
                path = str(definition["path"])
                if path == root:
                    continue
                field = path.removeprefix(root + ".")
                kind = KINDS.get(str(definition["objectType"]), str(definition["objectType"]))
                datatype = definition.get("valueDataType") or ""
                composite = composites.get(path, "")
                lines.append(
                    f"| `{field}` | {kind} | {datatype} | {_unit(definition)} "
                    f"| {_occurs(definition)} | {composite} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
